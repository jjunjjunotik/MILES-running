export function buildUserPrompt(input: {
  hand: string;
  finger: string;
  note: string;
}): string {
  const parts = [
    "아래 손톱 사진을 관찰하고 결과를 정리해 주세요.",
    `촬영 부위: ${input.hand} ${input.finger}`,
  ];
  if (input.note.trim()) {
    parts.push(`사용자가 남긴 메모: ${input.note.trim()}`);
  }
  parts.push(
    "메모는 참고만 하고, 관찰 내용은 사진에서 실제로 보이는 것에만 근거해 주세요.",
  );
  return parts.join("\n");
}
